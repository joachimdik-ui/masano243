-- Exécuter dans Supabase SQL Editor pour créer la table des flash infos.
create table if not exists public.flash (
  id bigint generated by default as identity primary key,
  info text not null
);

alter table public.flash enable row level security;

grant select on public.flash to anon, authenticated;
grant insert, update, delete on public.flash to authenticated;

drop policy if exists "Lecture publique des flash infos" on public.flash;
create policy "Lecture publique des flash infos"
  on public.flash
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Utilisateurs connectés peuvent créer des flash infos" on public.flash;
create policy "Utilisateurs connectés peuvent créer des flash infos"
  on public.flash
  for insert
  to authenticated
  with check (true);

drop policy if exists "Utilisateurs connectés peuvent modifier des flash infos" on public.flash;
create policy "Utilisateurs connectés peuvent modifier des flash infos"
  on public.flash
  for update
  to authenticated
  using (true)
  with check (true);

drop policy if exists "Utilisateurs connectés peuvent supprimer des flash infos" on public.flash;
create policy "Utilisateurs connectés peuvent supprimer des flash infos"
  on public.flash
  for delete
  to authenticated
  using (true);
